"""
The markwork command line: point it at a repository and it generates the
click-through Sphinx docs, with no conf.py, index.rst or scaffolding left
behind in the project.

The build is ephemeral. A throwaway conf.py and index.rst are written into
a temporary directory that doubles as the Sphinx source directory; the
'markwork_repo_root' config value points the engine back at the real
project, so its source is read in place and only the rendered HTML is
produced. The temporary directory is removed afterwards, so the repository
is never touched.
"""
#  Apache-2.0 license
#  Copyright (c) 2026 Asger Jon Vistisen

import argparse
import importlib.util
import os
import shutil
import sys
import tempfile
import webbrowser
from pathlib import Path

from sphinx.application import Sphinx
from sphinx.errors import SphinxError

from ._layout import detectLayout, readPyproject


def projectMeta(repoRoot) -> tuple:
  """Read the project name and version from a repo's pyproject.toml.

  Falls back to the repository directory name and an empty version when
  there is no pyproject.toml or it names neither, so the build always has a
  heading to render. When no TOML parser is available (Python 3.10
  without tomli), a small scan of the [project] table stands in, in the
  same dependency-free spirit as the dogfood conf.py.

  Parameters
  ----------
  repoRoot : str or Path
      The repository root to read.

  Returns
  -------
  tuple
      A pair '(name, version)' of strings.
  """
  repoRoot = Path(repoRoot)
  project = readPyproject(repoRoot).get("project", {})
  name, version = project.get("name"), project.get("version")
  if name or version:
    return name or repoRoot.name, version or ""
  pyproject = repoRoot / "pyproject.toml"
  name, version = repoRoot.name, ""
  if not pyproject.is_file():
    return name, version
  inProject = False
  for line in pyproject.read_text(encoding="utf-8").splitlines():
    stripped = line.strip()
    if stripped.startswith("[") and stripped.endswith("]"):
      inProject = stripped == "[project]"
      continue
    if not inProject or "=" not in stripped:
      continue
    key, _, raw = stripped.partition("=")
    value = _tomlString(raw)
    if key.strip() == "name":
      name = value
    elif key.strip() == "version":
      version = value
  return name, version


def _tomlString(raw: str) -> str:
  """The value of a simple TOML string, 'name = "x"  # note' giving 'x':
  the text between the opening quote and its match, or the bare text
  before any comment when unquoted."""
  value = raw.strip()
  quote = value[:1]
  if quote in ("'", '"'):
    end = value.find(quote, 1)
    return value[1:end] if end > 0 else value[1:]
  return value.partition("#")[0].strip()


def defaultTheme() -> str:
  """Return furo when it is installed, else Sphinx's built-in alabaster,
  so the command works even where furo was left out.

  Returns
  -------
  str
      The HTML theme name.
  """
  return "furo" if importlib.util.find_spec("furo") else "alabaster"


def writeWorkspace(
    work: Path, repoRoot: Path, srcRoot: str, testsRoot: str, package,
    project: str, release: str, theme: str
) -> None:
  """Write the throwaway conf.py and index.rst into the work directory.

  The conf enables only the markwork extension and the chosen theme, and
  hands the engine the repo root and the source, tests and package
  settings. The index gives the build its title and pulls in the package
  index the engine writes during the build.

  Parameters
  ----------
  work : Path
      The temporary Sphinx source directory.
  repoRoot : Path
      The repository being documented.
  srcRoot : str
      The source root, relative to the repo root.
  testsRoot : str
      The tests root, relative to the repo root.
  package : str or None
      The package name, or None to auto-detect.
  project : str
      The documentation title.
  release : str
      The version string shown in the header.
  theme : str
      The Sphinx HTML theme.
  """
  conf = "\n".join(
      [
        "#  Generated by markwork; ephemeral, safe to delete.",
        "project = %r" % project,
        "release = %r" % release,
        "version = %r" % release,
        'extensions = ["markwork"]',
        "html_theme = %r" % theme,
        "markwork_repo_root = %r" % str(repoRoot),
        "markwork_src_root = %r" % srcRoot,
        "markwork_tests_root = %r" % testsRoot,
        "markwork_package = %r" % package,
        'exclude_patterns = ["_build", ".doctrees"]',
        #  A page's rST is a generated wrapper around its source, so the
        #  theme's "view source" link and the copies behind it add weight
        #  and show nothing worth reading.
        "html_copy_source = False",
        "html_show_sourcelink = False",
        "",
      ]
  )
  (work / "conf.py").write_text(conf, encoding="utf-8")
  heading = project or repoRoot.name
  index = "\n".join(
      [
        heading,
        "=" * len(heading),
        "",
        ".. include:: _source/_packages.txt",
        "",
      ]
  )
  (work / "index.rst").write_text(index, encoding="utf-8")


def build(
    repo, *, srcRoot=None, testsRoot=None, package=None, output=None,
    theme=None, quiet=False, jobs=None
) -> Path:
  """Generate the markwork HTML for a repository and return the output dir.

  The source root and package are resolved by 'detectLayout' from what the
  project declares and from convention, and the tests are taken from
  'tests/'; each can be named instead. A temporary directory holds the generated conf.py and
  index.rst and serves as the Sphinx source directory; the engine reads the
  project's source in place via 'markwork_repo_root' and the HTML is built
  into the output directory. The temporary directory is removed afterwards,
  so the repository is left untouched.

  Parameters
  ----------
  repo : str or Path
      The repository root to document.
  srcRoot : str, optional
      The source root relative to the repo; auto-detected when omitted.
  testsRoot : str, optional
      The tests root relative to the repo; 'tests' when omitted.
  package : str, optional
      The package name; auto-detected when omitted.
  output : str or Path, optional
      The HTML output directory; a temporary one is made when omitted.
  theme : str, optional
      The Sphinx HTML theme; 'defaultTheme' picks one when omitted.
  quiet : bool
      Suppress Sphinx's progress output when True.
  jobs : int, optional
      The number of parallel Sphinx workers, one per CPU when omitted.
      markwork does its own work before Sphinx starts and declares itself
      safe for parallel writing, which is where a large project spends its
      time, so the pages come out identical either way.

  Returns
  -------
  Path
      The output directory the HTML was written to.
  """
  repoRoot = Path(repo).resolve()
  if not repoRoot.is_dir():
    raise NotADirectoryError(str(repoRoot))
  srcRoot, testsRoot, package = detectLayout(
      repoRoot, src=srcRoot, tests=testsRoot, package=package
  )
  project, release = projectMeta(repoRoot)
  theme = theme or defaultTheme()
  if not quiet:
    where = "the repo root" if srcRoot == "." else "%s/" % srcRoot
    print(
        "markwork: documenting %s under %s, tests: %s"
        % (package, where, testsRoot or "(none)")
    )
  if output is None:
    output = tempfile.mkdtemp(prefix="markwork-html-")
  output = Path(output).resolve()
  work = Path(tempfile.mkdtemp(prefix="markwork-conf-"))
  try:
    writeWorkspace(
        work, repoRoot, srcRoot, testsRoot or "tests", package, project,
        release, theme
    )
    workers = jobs if jobs is not None else os.cpu_count() or 1
    app = Sphinx(
        str(work), str(work), str(output), str(work / ".doctrees"), "html",
        status=None if quiet else sys.stdout, warning=sys.stderr,
        parallel=workers if workers > 1 else 0,
    )
    app.build()
  finally:
    shutil.rmtree(work, ignore_errors=True)
  return output


def main(argv=None) -> int:
  """Parse arguments and run an ephemeral markwork build.

  Parameters
  ----------
  argv : list of str, optional
      The argument vector; sys.argv is used when omitted.

  Returns
  -------
  int
      The process exit code.
  """
  parser = argparse.ArgumentParser(
      prog="markwork",
      description="Generate click-through Sphinx docs for a repository, "
                  "with no project setup.",
  )
  parser.add_argument(
      "repo", nargs="?", default=".", help="repository root (default: .)"
  )
  parser.add_argument(
      "-o", "--output", default=None,
      help="HTML output directory (default: a temporary directory)",
  )
  parser.add_argument(
      "--src", default=None,
      help="source root relative to the repo (default: auto-detect)",
  )
  parser.add_argument(
      "--tests", default=None,
      help="tests root relative to the repo (default: tests)",
  )
  parser.add_argument(
      "--package", default=None,
      help="package to document (default: auto-detect)",
  )
  parser.add_argument(
      "--theme", default=None,
      help="Sphinx HTML theme (default: furo if installed, else alabaster)",
  )
  parser.add_argument(
      "--open", action="store_true", dest="open_browser",
      help="open the rendered docs in a browser when done",
  )
  parser.add_argument(
      "-q", "--quiet", action="store_true",
      help="suppress Sphinx progress output",
  )
  parser.add_argument(
      "-j", "--jobs", type=int, default=None,
      help="parallel Sphinx workers (default: one per CPU)",
  )
  args = parser.parse_args(argv)
  try:
    output = build(
        args.repo, srcRoot=args.src, testsRoot=args.tests,
        package=args.package, output=args.output, theme=args.theme,
        quiet=args.quiet, jobs=args.jobs,
    )
  except (RuntimeError, NotADirectoryError) as error:
    print(str(error), file=sys.stderr)
    return 1
  except SphinxError as error:
    #  A bad theme, a broken extension and the like: Sphinx's own message
    #  is clear, so it is shown without the traceback.
    print("markwork: Sphinx stopped: %s" % error, file=sys.stderr)
    return 2
  index = output / "index.html"
  print("markwork: wrote %s" % index)
  if args.open_browser:
    webbrowser.open(index.as_uri())
  return 0
